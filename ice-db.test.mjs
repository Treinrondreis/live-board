import assert from 'node:assert/strict';
import {iceDbEvidence,iceEndpoint,sameIceStation} from './ice-db.mjs';
const now=Date.UTC(2026,9,27,14),time=now+600000;
const nl={code:'AH',name:'Arnhem Centraal',country:'NL',departure:now-600000};
const de={code:'DU',name:'Düsseldorf Hbf',country:'D',departure:time,arrival:time-120000};
const end={code:'EX',name:'Voorbeeld eindstation',country:'D',arrival:now+3600000};
const odd={number:'99101',serviceDate:'2026-10-27',stops:[nl,de,end]};
const row={number:odd.number,serviceDate:odd.serviceDate,category:'ICE',observedAt:de.name,plannedTimestamp:time,expectedTimestamp:time+300000,delay:5,hasRealtime:true,eventMode:'departure',retrievedAt:new Date(now).toISOString()};
assert.equal(iceDbEvidence(odd,[],[row],now).row,null);
const report={stationShortCode:'AH',departed:true,plannedTimestamp:now-600000,expectedTimestamp:now-600000,messageTimestamp:now};
assert.equal(iceDbEvidence(odd,[report],[row],now).row.source,'DB');
for(const change of [{serviceDate:'2026-10-26'},{number:'99103'},{retrievedAt:new Date(now-16*60000).toISOString()},{plannedTimestamp:time+6*60000},{hasRealtime:false}])assert.equal(iceDbEvidence(odd,[report],[{...row,...change}],now).row,null);
const even={...odd,number:'99102',stops:[{...end,arrival:null,departure:now-3600000},de,nl]};
const evenRow={...row,number:even.number};
assert.ok(iceDbEvidence(even,[],[evenRow],now).row);
assert.equal(iceDbEvidence(even,[report],[evenRow],now).row,null);
const arrival={...row,observedAt:end.name,eventMode:'arrival',plannedTimestamp:end.arrival,expectedTimestamp:end.arrival+300000};
assert.equal(iceEndpoint(end,'arrival',[],[arrival],now).expected,end.arrival+300000);
assert.equal(iceEndpoint(end,'arrival',[],[{...arrival,eventMode:'departure'}],now).expected,null);
assert.equal(iceEndpoint(end,'arrival',[],[],now).planned,end.arrival);
assert.equal(iceEndpoint(null,'arrival',[],[],now,'Gewijzigde bestemming').planned,null);
const hgl={code:'HGL',name:'Hengelo',country:'NL',departure:now-600000},bent={code:'BENT',name:'Bad Bentheim',country:'D',departure:time};
assert.ok(iceDbEvidence({...odd,stops:[hgl,bent,end]},[{...report,stationShortCode:'HGL'}],[{...row,observedAt:bent.name}],now).row);
assert.ok(iceDbEvidence({...even,stops:[end,bent,hgl]},[],[{...evenRow,observedAt:bent.name}],now).row);
console.log('ICE DB handoff: direction, boundary passage, date, station, event, freshness and endpoint modes passed');

assert.equal(sameIceStation("Frankfurt Flughafen","Frankfurt(M) Flughafen Fernbf"),true);
assert.equal(sameIceStation("Frankfurt Flughafen","Frankfurt(Main)Hbf"),false);
